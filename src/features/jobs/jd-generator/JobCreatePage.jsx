import { useState } from 'react';
import { useForm } from 'react-hook-form';
import { useQuery } from '@tanstack/react-query';
import { useNavigate } from 'react-router-dom';
import { departmentService } from '@/api/departmentService';
import { aiService } from '@/api/aiService';
import { jobService } from '@/api/jobService';
import { useToast } from '@/hooks/useToast';
import { Card } from '@/components/Card';
import { Input } from '@/components/Input';
import { Select } from '@/components/Select';
import { Button } from '@/components/Button';
import { SkillTag } from '@/components/SkillTag';
import { AiBadge } from '@/components/AiBadge';
import { getErrorMessage } from '@/utils/errors';
import { ContractType, ExperienceLevel, WorkMode } from '@/constants/enums';
import { ROUTES } from '@/constants/routes';
import {
  Sparkles,
  Plus,
  Send,
  RotateCcw,
  Edit3,
} from 'lucide-react';

export function JobCreatePage() {
  const navigate = useNavigate();
  const { success: toastSuccess, error: toastError } = useToast();

  const [skills, setSkills] = useState(['Java', 'Spring Boot', 'MySQL']);
  const [skillInput, setSkillInput] = useState('');
  const [isGenerating, setIsGenerating] = useState(false);
  const [isPublishing, setIsPublishing] = useState(false);
  const [isEditingDraft, setIsEditingDraft] = useState(false);

  // AI-generated draft state
  const [generatedJd, setGeneratedJd] = useState(null);

  // Departments list query
  const { data: departments = [] } = useQuery({
    queryKey: ['departments'],
    queryFn: () => departmentService.getAllDepartments(),
  });

  const { register, getValues } = useForm({
    defaultValues: {
      title: 'Senior Java Backend Engineer',
      departmentId: departments[0]?.id || 1,
      experienceLevel: ExperienceLevel.SENIOR,
      location: 'Casablanca',
      contractType: ContractType.CDI,
      workMode: WorkMode.HYBRID,
    },
  });

  const handleAddSkill = (e) => {
    e.preventDefault();
    const trimmed = skillInput.trim();
    if (trimmed && !skills.includes(trimmed)) {
      setSkills(prev => [...prev, trimmed]);
      setSkillInput('');
    }
  };

  const handleRemoveSkill = (skillToRemove) => {
    setSkills(prev => prev.filter(s => s !== skillToRemove));
  };

  const onGenerateWithAi = async () => {
    const values = getValues();
    if (!values.title?.trim()) {
      toastError('Please specify a job title first.');
      return;
    }

    setIsGenerating(true);
    try {
      const selectedDept = departments.find(d => String(d.id) === String(values.departmentId))?.name || 'Engineering';

      const result = await aiService.generateJobDescription({
        title: values.title,
        department: selectedDept,
        experienceLevel: values.experienceLevel,
        skills,
        location: values.location,
        contractType: values.contractType,
      });

      setGeneratedJd({
        title: result.title || values.title,
        description:
          result.description ||
          'We are seeking a seasoned Software Engineer to lead the design and implementation of distributed backend microservices.',
        responsibilities: result.responsibilities || [
          'Design robust RESTful APIs and asynchronous services.',
          'Lead architectural reviews and promote clean code practices.',
          'Optimize database queries and ensure high system uptime.',
        ],
        requiredSkills: result.requiredSkills || skills,
        conditions: result.conditions || 'Competitive salary, hybrid flexibility, health coverage.',
      });

      toastSuccess('Job description draft generated by AI.');
    } catch (err) {
      toastError(getErrorMessage(err, 'AI generation encountered an issue. Using standard template.'));
      // Fallback proposal
      setGeneratedJd({
        title: values.title,
        description: 'Lead engineering efforts in developing scalable cloud applications.',
        responsibilities: [
          'Design and maintain microservice APIs.',
          'Collaborate with front-end teams and product managers.',
          'Ensure high performance and security compliance.',
        ],
        requiredSkills: skills,
        conditions: 'Full-time CDI, comprehensive benefits package.',
      });
    } finally {
      setIsGenerating(false);
    }
  };

  const onPublishJob = async () => {
    if (!generatedJd) {
      toastError('Generate or review the job description before publishing.');
      return;
    }

    const values = getValues();
    setIsPublishing(true);

    try {
      const fullDescription = `
        <p>${generatedJd.description}</p>
        <h4>Key Responsibilities</h4>
        <ul>${generatedJd.responsibilities.map(r => `<li>${r}</li>`).join('')}</ul>
        <h4>Conditions & Benefits</h4>
        <p>${generatedJd.conditions}</p>
      `;

      const payload = {
        title: generatedJd.title || values.title,
        description: fullDescription,
        departmentId: Number(values.departmentId) || departments[0]?.id || 1,
        location: values.location,
        contractType: values.contractType,
        workMode: values.workMode,
        experienceLevel: values.experienceLevel,
        requiredSkills: generatedJd.requiredSkills || skills,
      };

      const createdJob = await jobService.createJob(payload);
      // Immediately publish to OPEN status
      await jobService.publishJob(createdJob.id);

      toastSuccess('Job offer published successfully.');
      navigate(ROUTES.RECRUITER_JOBS);
    } catch (err) {
      toastError(getErrorMessage(err, 'Failed to publish job offer. Please try again.'));
    } finally {
      setIsPublishing(false);
    }
  };

  return (
    <div>
      <div className="mb-4">
        <h1 className="fs-4 fw-bold text-dark mb-1">Create Job Offer with AI</h1>
        <p className="text-muted small mb-0">
          Define core job parameters and let the AI draft structured responsibilities and requirements.
        </p>
      </div>

      <div className="row g-4">
        {/* Left Panel: Inputs Form */}
        <div className="col-12 col-lg-5">
          <Card header={<div className="fw-semibold">1. Position Parameters</div>}>
            <form onSubmit={e => e.preventDefault()}>
              <Input
                label="Job Title"
                placeholder="e.g. Lead Spring Boot Architect"
                required
                {...register('title')}
              />

              <Select
                label="Department"
                required
                options={departments.map(d => ({ label: d.name, value: d.id }))}
                {...register('departmentId')}
              />

              <div className="row g-2">
                <div className="col-6">
                  <Select
                    label="Experience Level"
                    options={[
                      { label: 'Junior (0-2 yrs)', value: ExperienceLevel.JUNIOR },
                      { label: 'Mid-Level (3-5 yrs)', value: ExperienceLevel.MID },
                      { label: 'Senior (5+ yrs)', value: ExperienceLevel.SENIOR },
                    ]}
                    {...register('experienceLevel')}
                  />
                </div>
                <div className="col-6">
                  <Select
                    label="Contract Type"
                    options={[
                      { label: 'CDI (Permanent)', value: ContractType.CDI },
                      { label: 'CDD (Fixed-Term)', value: ContractType.CDD },
                      { label: 'Freelance', value: ContractType.FREELANCE },
                      { label: 'Stage', value: ContractType.STAGE },
                    ]}
                    {...register('contractType')}
                  />
                </div>
              </div>

              <div className="row g-2">
                <div className="col-6">
                  <Select
                    label="Location"
                    options={[
                      { label: 'Casablanca', value: 'Casablanca' },
                      { label: 'Rabat', value: 'Rabat' },
                      { label: 'Marrakech', value: 'Marrakech' },
                      { label: 'Tangier', value: 'Tangier' },
                    ]}
                    {...register('location')}
                  />
                </div>
                <div className="col-6">
                  <Select
                    label="Work Mode"
                    options={[
                      { label: 'Remote', value: WorkMode.REMOTE },
                      { label: 'Hybrid', value: WorkMode.HYBRID },
                      { label: 'On-site', value: WorkMode.ONSITE },
                    ]}
                    {...register('workMode')}
                  />
                </div>
              </div>

              {/* Skills Tag Input */}
              <div className="mb-3">
                <label htmlFor="required-skills-input" className="form-label">Required Skills</label>
                <div className="d-flex gap-2 mb-2">
                  <input
                    id="required-skills-input"
                    type="text"
                    className="form-control form-control-sm"
                    placeholder="e.g. Docker, Redis..."
                    value={skillInput}
                    onChange={e => setSkillInput(e.target.value)}
                    onKeyDown={e => {
                      if (e.key === 'Enter') {
                        e.preventDefault();
                        handleAddSkill(e);
                      }
                    }}
                  />
                  <Button type="button" size="sm" variant="secondary" onClick={handleAddSkill} icon={<Plus size={14} />}>
                    Add
                  </Button>
                </div>
                <div className="d-flex flex-wrap gap-1 p-2 bg-light border rounded">
                  {skills.map(s => (
                    <SkillTag key={s} name={s} onRemove={() => handleRemoveSkill(s)} />
                  ))}
                </div>
              </div>

              {/* Prominent Generate Button */}
              <div className="pt-2">
                <Button
                  type="button"
                  variant="ai"
                  className="w-100"
                  isLoading={isGenerating}
                  onClick={onGenerateWithAi}
                  icon={<Sparkles size={16} />}
                >
                  Generate with AI
                </Button>
              </div>
            </form>
          </Card>
        </div>

        {/* Right Panel: Live Document Preview */}
        <div className="col-12 col-lg-7">
          <Card
            className="h-100 border-success ai-container bg-white"
            header={
              <div className="d-flex align-items-center justify-content-between">
                <div className="d-flex align-items-center gap-2">
                  <AiBadge label="AI Draft Preview" />
                  <span className="fw-semibold text-dark">Live Job Description Preview</span>
                </div>
                {generatedJd && (
                  <div className="d-flex gap-1">
                    <Button
                      variant="secondary"
                      size="sm"
                      onClick={() => setIsEditingDraft(!isEditingDraft)}
                      icon={<Edit3 size={12} />}
                    >
                      {isEditingDraft ? 'View' : 'Edit'}
                    </Button>
                    <Button
                      variant="secondary"
                      size="sm"
                      onClick={onGenerateWithAi}
                      isLoading={isGenerating}
                      icon={<RotateCcw size={12} />}
                    >
                      Regenerate
                    </Button>
                  </div>
                )}
              </div>
            }
          >
            {!generatedJd ? (
              <div className="text-center py-5 text-muted">
                <Sparkles size={36} className="text-success mb-2 opacity-75" />
                <h3 className="fs-6 fw-semibold text-dark">No description generated yet</h3>
                <p className="small text-muted mb-0 mx-auto" style={{ maxWidth: '360px' }}>
                  Fill in the position parameters on the left and click &quot;Generate with AI&quot; to produce an editable preview.
                </p>
              </div>
            ) : isEditingDraft ? (
              /* Editable Mode */
              <div>
                <div className="mb-3">
                  <label htmlFor="edit-position-title" className="form-label">Position Title</label>
                  <input
                    id="edit-position-title"
                    type="text"
                    className="form-control"
                    value={generatedJd.title}
                    onChange={e => setGeneratedJd(prev => ({ ...prev, title: e.target.value }))}
                  />
                </div>
                <div className="mb-3">
                  <label htmlFor="edit-jd-desc" className="form-label">Description Summary</label>
                  <textarea
                    id="edit-jd-desc"
                    rows={4}
                    className="form-control"
                    value={generatedJd.description}
                    onChange={e => setGeneratedJd(prev => ({ ...prev, description: e.target.value }))}
                  />
                </div>
                <div className="mb-3">
                  <label htmlFor="edit-conditions" className="form-label">Conditions / Benefits</label>
                  <input
                    id="edit-conditions"
                    type="text"
                    className="form-control"
                    value={generatedJd.conditions}
                    onChange={e => setGeneratedJd(prev => ({ ...prev, conditions: e.target.value }))}
                  />
                </div>
                <div className="text-end">
                  <Button size="sm" variant="primary" onClick={() => setIsEditingDraft(false)}>
                    Save edits
                  </Button>
                </div>
              </div>
            ) : (
              /* Document Document View */
              <div className="p-3 bg-white border rounded">
                <h2 className="fs-5 fw-bold text-dark mb-2">{generatedJd.title}</h2>
                <p className="text-dark small leading-relaxed mb-4">{generatedJd.description}</p>

                <h3 className="fs-6 fw-bold text-dark mb-2">Key Responsibilities</h3>
                <ul className="small text-dark mb-4 ps-3">
                  {generatedJd.responsibilities.map((resp, idx) => (
                    <li key={idx} className="mb-1">
                      {resp}
                    </li>
                  ))}
                </ul>

                <h3 className="fs-6 fw-bold text-dark mb-2">Required Competencies</h3>
                <div className="d-flex flex-wrap gap-1 mb-4">
                  {(generatedJd.requiredSkills || []).map(skill => (
                    <SkillTag key={skill} name={skill} status="matching" />
                  ))}
                </div>

                <h3 className="fs-6 fw-bold text-dark mb-2">Benefits &amp; Work Conditions</h3>
                <p className="text-muted small mb-0">{generatedJd.conditions}</p>
              </div>
            )}

            {/* Bottom Publish Bar */}
            {generatedJd && (
              <div className="d-flex justify-content-between align-items-center mt-4 pt-3 border-top">
                <span className="text-muted small">Nothing is saved until you click Publish.</span>
                <Button
                  variant="primary"
                  isLoading={isPublishing}
                  onClick={onPublishJob}
                  icon={<Send size={14} />}
                >
                  Publish job offer
                </Button>
              </div>
            )}
          </Card>
        </div>
      </div>
    </div>
  );
}
